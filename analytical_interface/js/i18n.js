  function detectLang() {
    const list = (navigator.languages && navigator.languages.length) ? navigator.languages : [navigator.language || "en"];
    for (const tag of list) {
      const base = String(tag || "").toLowerCase().split("-")[0];
      if (SUPPORTED.includes(base)) return base;
    }
    return "en";
  }

  let current = detectLang();

  function t(key, vars) {
    const table = STRINGS[current] || STRINGS.en;
    const text = table[key] ?? STRINGS.en[key] ?? key;
    if (!vars) return text;
    return text.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? ""));
  }

  // `choice` is "auto" or one of SUPPORTED.
  function setLang(choice) {
    current = SUPPORTED.includes(choice) ? choice : detectLang();
    document.documentElement.setAttribute("lang", LOCALES[current]);
    document.title = t("app.title");
    return current;
  }

  window.I18N = {
    SUPPORTED,
    detectLang,
    setLang,
    t,
    locale: () => LOCALES[current],
    get lang() { return current; },
  };
  window.t = t;
  setLang("auto");
